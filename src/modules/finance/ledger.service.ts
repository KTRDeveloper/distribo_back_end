import type { LedgerEntry, LedgerEntryKind, Prisma } from '@prisma/client';
import { httpError } from '../../lib/http-error.js';
import { addAmountHeld } from '../organization/organization.repository.js';
import { addToBalance, resolveMergedRelation } from '../relationship/relationship.repository.js';

export type LedgerMode = 'CASH' | 'MOBILE_MONEY';

export type LedgerInput = {
  id: string;
  relationshipId: string;
  kind: LedgerEntryKind;
  amount: bigint;
  mode?: LedgerMode;
  orderId?: string;
  transactionReference?: string;
  note?: string;
  recordedById: string;
  organizationId: string;
  occurredAt: Date;
};

type EntryRow = {
  id: string;
  relationshipId: string;
  kind: LedgerEntryKind;
  amount: bigint;
  mode?: LedgerMode;
  orderId?: string;
  transactionReference?: string;
  note?: string;
  recordedById: string;
  /** Person whose held money changes, when not the recorder (reversals). */
  heldById?: string;
  occurredAt: Date;
  reversesEntryId?: string;
};

function notFound() {
  return httpError(404, 'NOT_FOUND', 'Not found');
}

/** Rejects what the database would refuse later with an opaque error (C-23). */
function assertValid(input: Pick<LedgerInput, 'kind' | 'amount' | 'mode'>): void {
  const cashKind = input.kind === 'PAYMENT' || input.kind === 'REFUND';
  if (input.amount <= 0n || cashKind !== (input.mode !== undefined)) {
    throw httpError(400, 'VALIDATION_ERROR', 'Invalid ledger entry');
  }
}

/**
 * Cash effect of an entry on the recorder's amount held (CM-17): a PAYMENT brings money in, a
 * REFUND sends it out, a reversal counts the other way; other kinds are not cash.
 */
function heldEffect(kind: LedgerEntryKind, amount: bigint, isReversal: boolean): bigint {
  if (kind !== 'PAYMENT' && kind !== 'REFUND') return 0n;
  const effect = kind === 'PAYMENT' ? amount : -amount;
  return isReversal ? -effect : effect;
}

/**
 * Inserts the entry, then applies its effects in the C-37 order: relationship balance first,
 * recorder's amount held second. `balance_effect` is generated by the database, so the balance
 * moves by the value read back from the inserted row, never by a client-side sign.
 */
async function insertAndApply(
  tx: Prisma.TransactionClient,
  row: EntryRow,
  organizationId: string
): Promise<LedgerEntry> {
  const entry = await tx.ledgerEntry.create({
    data: {
      id: row.id,
      customerRelationshipId: row.relationshipId,
      orderId: row.orderId ?? null,
      kind: row.kind,
      amount: row.amount,
      mode: row.mode ?? null,
      transactionReference: row.transactionReference ?? null,
      reversesEntryId: row.reversesEntryId ?? null,
      recordedById: row.recordedById,
      note: row.note ?? null,
      occurredAt: row.occurredAt,
    },
  });

  await addToBalance(tx, entry.customerRelationshipId, entry.balanceEffect);

  const held = heldEffect(entry.kind, entry.amount, entry.reversesEntryId !== null);
  if (held !== 0n) await addAmountHeld(tx, row.heldById ?? entry.recordedById, organizationId, held);
  return entry;
}

/**
 * Writes one ledger entry and updates the caches in the caller's transaction (C-37, CM-17;
 * ASVS v5.0.0-2.3.3, v5.0.0-2.3.4). Both caches change by `SET x = x + delta`, the relationship
 * before the collaboration, so concurrent writes never lose an effect and writers lock in one
 * order. A failure anywhere aborts the caller's transaction: no entry, no cache change remains.
 *
 * @param tx - The caller's transaction.
 * @param input - Entry fields; `relationshipId` may be a merged duplicate, the entry is then
 *   written on the surviving relationship.
 * @returns The stored entry, including its generated `balanceEffect`.
 * @throws 400 VALIDATION_ERROR for an amount not above zero or a mode that does not fit the kind.
 * @throws 404 NOT_FOUND for an unknown relationship or a recorder who is not a collaborator.
 */
export async function appendLedgerEntry(
  tx: Prisma.TransactionClient,
  input: LedgerInput
): Promise<LedgerEntry> {
  assertValid(input);
  const relationshipId = await resolveMergedRelation(input.relationshipId, tx);
  const live = await tx.customerRelationship.findFirst({
    where: { id: relationshipId, deletedAt: null },
    select: { id: true },
  });
  if (!live) throw notFound();

  return insertAndApply(
    tx,
    {
      id: input.id,
      relationshipId,
      kind: input.kind,
      amount: input.amount,
      mode: input.mode,
      orderId: input.orderId,
      transactionReference: input.transactionReference,
      note: input.note,
      recordedById: input.recordedById,
      occurredAt: input.occurredAt,
    },
    input.organizationId
  );
}

/**
 * Appends the mirror of an entry: same relationship, kind, amount, mode and order, pointing at it
 * through `reverses_entry_id`, so its effects are the opposite of the original (CM-17). The
 * database refuses a second reversal, a reversal of a reversal and any mismatch (C-25).
 *
 * The held-money effect goes to the collaboration of `input.heldById` in the supplier
 * organization of the relationship: the person who took (or gave) the cash of the original entry,
 * so a reversed entry counts the other way in the held money of the person it first counted for
 * (CM-17, FIN-009 AC-1). It defaults to `input.recordedById`, the person writing the reversal.
 *
 * @param tx - The caller's transaction.
 * @param entryId - The entry to reverse.
 * @param input - New entry id, the person reversing, an optional note and, when it differs from
 *   the person reversing, the person whose held money the original entry changed.
 * @returns The stored reversal entry.
 * @throws 404 NOT_FOUND when the entry, its relationship or the recorder's collaboration is absent.
 */
export async function reverseLedgerEntry(
  tx: Prisma.TransactionClient,
  entryId: string,
  input: { id: string; recordedById: string; heldById?: string; note?: string }
): Promise<LedgerEntry> {
  const target = await tx.ledgerEntry.findUnique({
    where: { id: entryId },
    include: { customerRelationship: { select: { supplierOrganizationId: true } } },
  });
  const organizationId = target?.customerRelationship.supplierOrganizationId;
  if (!target || !organizationId) throw notFound();

  return insertAndApply(
    tx,
    {
      id: input.id,
      relationshipId: target.customerRelationshipId,
      kind: target.kind,
      amount: target.amount,
      mode: target.mode ?? undefined,
      orderId: target.orderId ?? undefined,
      note: input.note,
      recordedById: input.recordedById,
      heldById: input.heldById,
      occurredAt: new Date(),
      reversesEntryId: target.id,
    },
    organizationId
  );
}
