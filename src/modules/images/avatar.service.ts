import { httpError } from '../../lib/http-error.js';
import { imageUrl } from '../../lib/image-keys.js';
import { logger } from '../../lib/logger.js';
import { setAvatarKey } from '../person/person.repository.js';
import { deleteImageFiles, storeUploadedImage } from './image.service.js';

/**
 * True when the database refused a photo for a guest or an anonymized person (PER-010): the
 * driver error names the CHECK that failed. Any other error is not ours to map.
 */
function isAvatarCheckViolation(err: unknown): boolean {
  const message = err instanceof Error ? err.message : '';
  return /people_(guest|anonymized)_avatar_check/.test(message);
}

/** Runs the key write; maps the database refusal for a guest or anonymized person to 409. */
async function writeKey(personId: string, key: string | null): Promise<string | null> {
  try {
    return await setAvatarKey(personId, key);
  } catch (err) {
    if (isAvatarCheckViolation(err)) {
      throw httpError(409, 'AVATAR_NOT_ALLOWED', 'This account cannot have a profile photo');
    }
    throw err;
  }
}

/**
 * Stores a new profile photo for the session person and returns its address (C-49, C-50).
 * Order: check and store the new file, write the key in one transaction (`setAvatarKey`),
 * then delete the previous file. If the write fails the new file is deleted at once, so
 * nothing is left behind and the key is unchanged. The person always comes from the session
 * and the key is generated by the server (ASVS v5.0.0-8.2.2, v5.0.0-15.3.3).
 * @throws {HttpError} 400 `UNSUPPORTED_IMAGE` / `IMAGE_TOO_LARGE` / `VALIDATION_ERROR`,
 * 409 `AVATAR_NOT_ALLOWED` for a guest or an anonymized person.
 */
export async function replaceAvatar(
  personId: string,
  bytes: Buffer
): Promise<{ avatar_url: string }> {
  const key = await storeUploadedImage('avatars', bytes);

  let previous: string | null;
  try {
    previous = await writeKey(personId, key);
  } catch (err) {
    await deleteImageFiles([key]);
    throw err;
  }

  if (previous !== null) await deleteImageFiles([previous]);
  logger.info({ event: 'avatar_changed', personId }, 'Avatar changed');
  return { avatar_url: imageUrl(key)! };
}

/**
 * Clears the session person's profile photo and deletes the file; a repeat changes nothing.
 * @throws {HttpError} 404 `NOT_FOUND` when the person no longer exists.
 */
export async function removeAvatar(personId: string): Promise<void> {
  const previous = await writeKey(personId, null);
  if (previous !== null) await deleteImageFiles([previous]);
  logger.info({ event: 'avatar_changed', personId }, 'Avatar changed');
}
